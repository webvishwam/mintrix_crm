/**
 * THE WORK MODEL — one object, not four.
 *
 * `work_items` is the only place operational work lives. A lightweight action ("Call
 * Priya") and an operational ticket ("Prepare the recording setup") differ by the
 * fields they carry, not by living in separate systems with separate queues, separate
 * SLA logic and separate ideas of what "done" means.
 *
 * BLOCKING is the load-bearing flag: only blocking work can hold a stage shut, which
 * is why Production can edit an episode for a week without stopping the sale.
 */

export const ACTIVE = "('open','in_progress','waiting','blocked')";
export type WorkStatus = "open" | "in_progress" | "waiting" | "blocked"
  | "resolved" | "cancelled";

export const STATUSES: { key: WorkStatus; name: string; what: string }[] = [
  { key: "open", name: "Open", what: "Not started." },
  { key: "in_progress", name: "In progress", what: "Somebody is on it." },
  { key: "waiting", name: "Waiting", what: "Somebody else has to move first." },
  { key: "blocked", name: "Blocked", what: "It cannot proceed." },
  { key: "resolved", name: "Resolved", what: "Done, with a note saying what was done." },
  { key: "cancelled", name: "Cancelled", what: "It should not be done at all." },
];

export const RESOLUTIONS: [string, string, string][] = [
  ["completed", "Completed", "It is done, as described."],
  ["completed_with_issue", "Completed with an issue",
   "Done, but something went wrong that somebody should know about."],
  ["follow_up_required", "Completed — follow-up required",
   "Done, and it produced something else that needs doing."],
  ["no_longer_required", "No longer required", "It does not need doing. Say why."],
  ["other", "Other", "Anything the four above do not cover."],
];

const BANNED = [/^follow[- ]?up$/i, /^check in$/i, /^touch base$/i, /^circle back$/i,
                /^chase$/i, /^ping\b/i];

export interface CreateWork {
  accountId: string;
  schoolId?: string | null;
  title: string;
  reason: string;
  team: Team | string;
  workstream: Workstream | string;
  taskType: string;
  ownerId?: string | null;
  requesterId?: string | null;
  personId?: string | null;
  externalPersonId?: string | null;
  opportunityId?: string | null;
  podcastId?: string | null;
  deliveryId?: string | null;
  requiredOutcome?: string | null;
  dependsOn?: string | null;
  blocking?: boolean;
  stage?: string | null;
  templateKey?: string | null;
  slaHours?: number;
  priority?: string;
  autoGenerated?: boolean;
}

/**
 * The ONE way work is created. Every stage entry, every form and every action calls
 * this — there is no second creator anywhere.
 */
export async function create(w: CreateWork): Promise<string> {
  const title = w.title.trim();
  if (!title) throw new Error("Say what needs to happen.");
  if (BANNED.some((re) => re.test(title))) {
    throw new Error(
      `"${title}" is not an action. Write a verb and an object — what exactly will ` +
      "you do, and to what?");
  }
  if (!w.reason.trim()) {
    throw new Error("Say why this is the right thing to do. Without it the record " +
                    "counts as stalled.");
  }

  // Idempotency. Stage work is identified by its template, so a school re-entering a
  // stage gets the work it already has rather than a second copy of it.
  if (w.templateKey && w.schoolId) {
    const same = await db.one(
      `select id from public.work_items
        where school_id = ?
          and stage is not distinct from ?::journey_stage
          and template_key = ?
          and status in ${ACTIVE}`,
      [w.schoolId, w.stage ?? null, w.templateKey]);
    if (same) return same.id as string;
  }
  const dupe = await db.one(
    `select id from public.work_items
      where account_id = ? and lower(btrim(title)) = lower(btrim(?))
        and coalesce(school_id,'') = coalesce(?,'')
        and status in ${ACTIVE}`,
    [w.accountId, title, w.schoolId ?? null]);
  if (dupe) return dupe.id as string;

  const hours = w.slaHours ?? 48;
  const id = await db.insert("work_items", {
    account_id: w.accountId, school_id: w.schoolId ?? null,
    person_id: w.personId ?? null, opportunity_id: w.opportunityId ?? null,
    podcast_id: w.podcastId ?? null, delivery_id: w.deliveryId ?? null,
    work_type: w.templateKey || w.externalPersonId ? "ticket" : "task",
    task_type: w.taskType, title, reason: w.reason.trim(),
    required_outcome: w.requiredOutcome ?? null,
    team: w.team, workstream: w.workstream,
    stage: w.stage ?? null, template_key: w.templateKey ?? null,
    blocking: !!w.blocking, status: "open", priority: w.priority ?? "normal",
    owner_id: w.ownerId ?? db.currentUserId(),
    requester_id: w.requesterId ?? db.currentUserId(),
    external_person_id: w.externalPersonId ?? null,
    depends_on_id: w.dependsOn ?? null,
    due_at: db.plusHours(hours), sla_hours: hours,
    auto_generated: !!w.autoGenerated,
  });
  await audit.record({
    action: "WORK_CREATED", objectType: "work_item", objectId: id,
    accountId: w.accountId, schoolId: w.schoolId ?? null,
    after: { title, team: w.team, workstream: w.workstream, blocking: !!w.blocking },
  });
  return id;
}

/** Work that already looks like this. Shown to a human — never merged, never skipped. */
export async function similar(accountId: string, title: string,
                              schoolId?: string | null): Promise<db.Row[]> {
  const words = title.toLowerCase().split(/\W+/).filter((w) => w.length > 3);
  if (!words.length) return [];
  const rows = await db.many(
    `select * from public.work_items
      where account_id = ? and status in ${ACTIVE}
        and coalesce(school_id,'') = coalesce(?,'')`, [accountId, schoolId ?? null]);
  return rows.filter((t) => {
    const other = String(t.title).toLowerCase();
    const shared = words.filter((w) => other.includes(w)).length;
    return shared >= Math.max(2, Math.ceil(words.length * 0.6));
  });
}

/** The unresolved prerequisite, if there is one. Blocked by WORK, not by a person. */
export async function blockedBy(item: db.Row): Promise<db.Row | null> {
  if (!item.depends_on_id) return null;
  const dep = await db.get("work_items", item.depends_on_id as string);
  if (!dep) return null;
  return ["resolved", "cancelled"].includes(String(dep.status)) ? null : dep;
}

export interface Resolution { kind: string; note: string }

/** Opening something is not finishing it. The owner says what was done. */
export async function resolve(id: string, r: Resolution): Promise<void> {
  const t = await db.get("work_items", id);
  if (!t) throw new Error("That work item no longer exists.");
  if (t.status === "resolved") throw new Error("That work item is already resolved.");
  if (t.status === "cancelled") {
    throw new Error("That work item was cancelled. Its history is not reopened.");
  }
  const dep = await blockedBy(t);
  if (dep) {
    throw new Error(`"${dep.title}" has to be resolved first — this depends on it.`);
  }
  if (!r.note?.trim()) {
    throw new Error("Say what was done. A resolution with no note is a guess.");
  }
  await db.transaction(async () => {
    await db.update("work_items", id, {
      status: "resolved", resolution_kind: r.kind, resolution_note: r.note.trim(),
      resolved_by: db.currentUserId(), completed_at: db.now(),
    });
    await activity.log({
      accountId: t.account_id as string, schoolId: t.school_id as string | null,
      personId: t.person_id as string | null,
      opportunityId: t.opportunity_id as string | null,
      podcastId: t.podcast_id as string | null, workItemId: id,
      type: "work_resolved", direction: "internal", outcomeKey: r.kind,
      outcomeLabel: RESOLUTIONS.find(([k]) => k === r.kind)?.[1] ?? "Resolved",
      summary: `${t.title} — ${r.note.trim()}`,
    });
    await audit.record({
      action: "WORK_RESOLVED", objectType: "work_item", objectId: id,
      accountId: t.account_id as string, schoolId: t.school_id as string | null,
      before: { status: t.status }, after: { status: "resolved", kind: r.kind },
      reason: r.note.trim(),
    });
  });
}

export interface StatusChange {
  status: WorkStatus;
  waitingOn?: string | null;
  followUpOn?: string | null;
  reason?: string | null;
}

export async function setStatus(id: string, c: StatusChange): Promise<void> {
  const t = await db.get("work_items", id);
  if (!t) throw new Error("That work item no longer exists.");
  if (t.status === "resolved") {
    throw new Error("That work item is already resolved. Its history is not reopened.");
  }
  if (["waiting", "blocked"].includes(c.status)) {
    if (!c.reason?.trim()) {
      throw new Error("Say what it is waiting on. A parked item with no reason is a " +
                      "forgotten one.");
    }
    if (c.status === "waiting" && !c.followUpOn) {
      throw new Error("Say when to come back to it.");
    }
  }
  if (c.status === "cancelled" && !c.reason?.trim()) {
    throw new Error("Say why it should not be done. Cancelled is not resolved, and " +
                    "the history keeps them apart.");
  }
  await db.transaction(async () => {
    await db.update("work_items", id, {
      status: c.status,
      waiting_on: c.waitingOn ?? t.waiting_on,
      follow_up_on: c.followUpOn ?? t.follow_up_on,
      blocked_reason: c.reason ?? t.blocked_reason,
      resolution_note: c.status === "cancelled" ? c.reason : t.resolution_note,
      started_at: c.status === "in_progress" && !t.started_at ? db.now() : t.started_at,
    });
    await audit.record({
      action: c.status === "cancelled" ? "WORK_CANCELLED" : "WORK_STATUS_CHANGED",
      objectType: "work_item", objectId: id,
      accountId: t.account_id as string, schoolId: t.school_id as string | null,
      before: { status: t.status }, after: { status: c.status },
      reason: c.reason ?? null,
    });
  });
}

export async function assign(id: string, ownerId: string | null, why?: string) {
  const t = await db.get("work_items", id);
  if (!t) throw new Error("That work item no longer exists.");
  await db.transaction(async () => {
    await db.update("work_items", id, { owner_id: ownerId });
    await audit.record({
      action: "WORK_ASSIGNED", objectType: "work_item", objectId: id,
      accountId: t.account_id as string, schoolId: t.school_id as string | null,
      before: { owner_id: t.owner_id }, after: { owner_id: ownerId },
      reason: why ?? null,
    });
  });
}

