const DECORATE = `
  select w.*,
         o.full_name  as owner_name,
         rq.full_name as requester_name,
         s.name       as school_name,
         a.name       as account_name,
         ep.name      as external_person_name,
         dep.title    as blocked_by_title,
         dep.id       as blocked_by_id
    from public.work_items w
    left join public.profiles o  on o.id = w.owner_id
    left join public.profiles rq on rq.id = w.requester_id
    left join public.schools s   on s.id = w.school_id
    left join public.accounts a  on a.id = w.account_id
    left join public.people ep   on ep.id = w.external_person_id
    left join public.work_items dep on dep.id = w.depends_on_id
      and dep.status not in ('resolved','cancelled')`;

export const withNames = (where: string, args: unknown[] = [], order = "w.due_at") =>
  db.many(`${DECORATE} where ${where} order by ${order}`, args);

export const byId = async (id: string) =>
  (await db.many(`${DECORATE} where w.id = ?`, [id]))[0] ?? null;

export interface Workboard {
  groups: { key: string; name: string; items: db.Row[] }[];
  counts: { active: number; overdue: number; waiting: number; blocked: number };
}

/** Everything happening around one school, grouped by workstream. */
export async function schoolBoard(schoolId: string, filter: {
  team?: string | null; workstream?: string | null; ownerId?: string | null;
  status?: string | null;
} = {}): Promise<Workboard> {
  const where = [`w.school_id = ?`, `w.status in ${ACTIVE}`];
  const args: unknown[] = [schoolId];
  if (filter.team) { where.push("w.team = ?::mintrix_team"); args.push(filter.team); }
  if (filter.workstream) {
    where.push("w.workstream = ?::workstream"); args.push(filter.workstream);
  }
  if (filter.ownerId) { where.push("w.owner_id = ?"); args.push(filter.ownerId); }
  if (filter.status) { where.push("w.status = ?::work_status"); args.push(filter.status); }

  const rows = await withNames(where.join(" and "), args, "w.blocking desc, w.due_at");
  const groups: Workboard["groups"] = [];
  for (const ws of ["acquisition", "podcast", "production", "commercial",
                    "school_data", "pilot", "implementation", "contract", "onboarding"]) {
    const items = rows.filter((r) => r.workstream === ws);
    if (items.length) groups.push({ key: ws, name: workstreamName(ws), items });
  }
  const now = db.now();
  return {
    groups,
    counts: {
      active: rows.length,
      overdue: rows.filter((r) => ["open", "in_progress"].includes(String(r.status))
        && String(r.due_at) < now).length,
      waiting: rows.filter((r) => r.status === "waiting").length,
      blocked: rows.filter((r) => r.status === "blocked").length,
    },
  };
}

export interface MyWork {
  overdue: db.Row[]; today: db.Row[]; upcoming: db.Row[];
  waiting: db.Row[]; blocked: db.Row[]; resolvedToday: db.Row[];
}

export async function mine(userId: string): Promise<MyWork> {
  const rows = await withNames(`w.owner_id = ? and w.status in ${ACTIVE}`, [userId]);
  const now = db.now();
  const today = db.today();
  const live = rows.filter((r) => ["open", "in_progress"].includes(String(r.status)));
  return {
    overdue: live.filter((r) => String(r.due_at) < now),
    today: live.filter((r) => String(r.due_at) >= now
      && String(r.due_at).slice(0, 10) === today),
    upcoming: live.filter((r) => String(r.due_at).slice(0, 10) > today),
    waiting: rows.filter((r) => r.status === "waiting"),
    blocked: rows.filter((r) => r.status === "blocked"),
    resolvedToday: await withNames(
      `w.resolved_by = ? and w.status = 'resolved'
         and w.completed_at::date = current_date`, [userId], "w.completed_at desc"),
  };
}

/** Who is expected to act, in words, with no ambiguity. */
export async function actionOwner(t: db.Row) {
  const dep = await blockedBy(t);
  return {
    owner: (t.owner_name as string) ?? "unassigned",
    internal: teamName(t.team as string),
    waitingOn: t.status === "waiting" ? (t.waiting_on as string) ?? "the school" : null,
    external: (t.external_person_name as string) ?? null,
    blockedBy: dep ? (dep.title as string) : null,
  };
}

/** Work that cannot be acted on because it is missing its context. */
export async function orphaned(): Promise<{ item: db.Row; why: string[] }[]> {
  const rows = await db.many(
    `select * from public.work_items where status in ${ACTIVE}`);
  const out: { item: db.Row; why: string[] }[] = [];
  for (const t of rows) {
    const why: string[] = [];
    if (!t.owner_id) why.push("nobody owns it");
    if (!t.team) why.push("no team");
    if (t.work_type === "ticket" && !t.school_id && !t.opportunity_id && !t.podcast_id) {
      why.push("no school or business context");
    }
    if (why.length) out.push({ item: t, why });
  }
  return out;
}
